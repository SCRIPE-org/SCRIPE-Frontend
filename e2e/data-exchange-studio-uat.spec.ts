interface DescriptorColumnDto {
  key: string;
  displayNameEn: string;
  displayNameAr: string;
  dataType: string;
  isRequired: boolean;
  isMappable: boolean;
  isAutoGenerated?: boolean;
  direction?: string;
  allowedValues?: string[];
  lookupEntityKey?: string | null;
}

interface DescriptorPayload {
  descriptor?: {
    entityKey?: string;
    columns?: DescriptorColumnDto[];
  };
  columns?: DescriptorColumnDto[];
}

function extractColumns(payload: DescriptorPayload | null): DescriptorColumnDto[] {
  if (!payload) return [];
  if (Array.isArray(payload.descriptor?.columns)) {
    return payload.descriptor!.columns!;
  }
  if (Array.isArray(payload.columns)) {
    return payload.columns;
  }
  return [];
}

function getMappableColumns(payload: DescriptorPayload | null): DescriptorColumnDto[] {
  return extractColumns(payload).filter(
    (c) =>
      c.isMappable !== false &&
      c.direction !== "ExportOnly" &&
      c.key.toLowerCase() !== "id"
  );
}

/**
 * Asserts that the page has zero horizontal overflow at 1440x900.
 */
async function assertZeroHorizontalOverflow(page: Page): Promise<void> {
  const overflowPx = await page.evaluate(
    () => document.documentElement.scrollWidth - window.innerWidth
  );
  expect(overflowPx).toBeLessThanOrEqual(2);
}

/**
 * Waits for fonts, decoded images, zero skeleton/spinner placeholders, and 2 animation frames
 * before capturing a deterministic 1440x900 screenshot (zero arbitrary sleep timers).
 */
async function captureSteadyScreenshot(
  page: Page,
  fileName: string,
  readyLocator?: Locator
): Promise<string> {
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.waitForLoadState("domcontentloaded");
  if (readyLocator) {
    await expect(readyLocator).toBeVisible({ timeout: 25_000 });
  }
  await expect(page.locator("[data-slot='skeleton']")).toHaveCount(0, {
    timeout: 15_000,
  });
  await page.evaluate(async () => {
    if ("fonts" in document) {
      await (document as Document & { fonts: FontFaceSet }).fonts.ready;
    }
    const imgs = Array.from(document.querySelectorAll("img"));
    await Promise.all(
      imgs.map((img) =>
        img.complete
          ? Promise.resolve()
          : new Promise<void>((resolve) => {
              img.addEventListener("load", () => resolve(), { once: true });
              img.addEventListener("error", () => resolve(), { once: true });
            })
      )
    );
    await new Promise<void>((resolve) =>
      requestAnimationFrame(() => requestAnimationFrame(() => resolve()))
    );
  });
  const targetPath = path.join(SCREENSHOT_DIR, fileName);
  await page.screenshot({
    path: targetPath,
    fullPage: false,
    animations: "disabled",
  });
  expect(fs.existsSync(targetPath)).toBe(true);
  expect(fs.statSync(targetPath).size).toBeGreaterThan(5_000);
  return targetPath;
}

/**
 * Opens the compact Data Exchange dropdown menu (`dx-trigger-${entityKey}`)
 * and clicks the target item (`actionTestId`).
 */
async function openDxDropdownAndClick(
  page: Page,
  entityKey: string,
  actionTestId: string
): Promise<void> {
  const trigger = page.getByTestId(`dx-trigger-${entityKey}`).first();
  await expect(trigger).toBeVisible({ timeout: 25_000 });
  const item = page.getByTestId(actionTestId).first();
  if (!(await item.isVisible().catch(() => false))) {
    await trigger.click();
  }
  await expect(item).toBeVisible({ timeout: 10_000 });
  await item.click();
}

/**
 * Logs in via the real `/login` page against live `:5035` API.
 */
async function loginRealSession(
  page: Page,
  redirectPath: string,
  email: string
): Promise<void> {
  const password = getDevAdminPassword();
  await page.goto(`/login?redirect=${encodeURIComponent(redirectPath)}`);
  await page.waitForLoadState("domcontentloaded");

  const emailInput = page.locator("#identifier");
  const passwordInput = page.locator("#password");
  await expect(emailInput).toBeVisible({ timeout: 20_000 });
  await emailInput.fill(email);
  await passwordInput.fill(password);

  await page.locator('button[type="submit"]').click();

  await page.waitForURL(
    (url) => !url.pathname.includes("/login"),
    { timeout: 30_000 }
  );
  await page.waitForLoadState("domcontentloaded");
}

