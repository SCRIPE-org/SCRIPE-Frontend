/**
 * Option-set Arabic copy — namespace `optionSet`.
 *
 * A strict key-for-key mirror of option-set.en.ts. The mirror is a hard requirement rather than a
 * nicety: the translator in this codebase has no defaultValue fallback, so any key present in `en`
 * and missing here renders the raw English sentence to an Arabic-speaking administrator, and nothing
 * else in the suite would notice. optionSet.locale.test.ts asserts the two key sets are identical.
 *
 * Translation decisions worth recording, because a later editor would otherwise "correct" them:
 *
 *  - Version statuses are translated as states, not as transliterations: Draft = "مسودة",
 *    Published = "منشور", Deprecated = "مُهمَل", Archived = "مؤرشف". "مُهمَل" is the load-bearing
 *    one — the copy has to make clear a deprecated version is superseded, not erased, since records
 *    that reference it still render.
 *  - The set's members are called "خيارات" (choices/options), matching the English copy's "option",
 *    even though the keys mirror the wire's `items`.
 *  - Deactivation is "إيقاف", never "حذف". This UI cannot delete an option, and Arabic copy that
 *    used the word for deletion would promise something the screen deliberately refuses to do.
 *  - The `placeholders` blocks keep language-neutral sample values (an English label sample, a hex
 *    colour, an icon name) because they demonstrate the format of the input, not prose to translate.
 */

