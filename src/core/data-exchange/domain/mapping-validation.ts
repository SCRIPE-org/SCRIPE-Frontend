const ARABIC_INDIC_MAP: Record<string, string> = {
  "٠": "0",
  "١": "1",
  "٢": "2",
  "٣": "3",
  "٤": "4",
  "٥": "5",
  "٦": "6",
  "٧": "7",
  "٨": "8",
  "٩": "9",
  "٫": ".",
  "،": ",",
};

const MASKED_SENTINEL_TOKENS = new Set([
  "REDACTED",
  "[REDACTED]",
  "MASKED",
  "[MASKED]",
]);

/**
 * Detects redacted UI/export sentinel tokens ("••••••", "***", "[REDACTED]", "[MASKED]")
 * so roundtrip re-imports of exported workbooks never trigger false-positive type errors.
 */
export function isMaskedSentinelSample(raw: string): boolean {
  const trimmed = raw.trim();
  if (!trimmed) return false;
  if (MASKED_SENTINEL_TOKENS.has(trimmed.toUpperCase())) return true;
  if (trimmed.length < 3) return false;
  for (const ch of trimmed) {
    if (ch !== "•" && ch !== "*" && ch !== "●" && ch !== "X") {
      return false;
    }
  }
  return true;
}

/** Normalizes Arabic-Indic numerals in a cell string for preview validation. */
export function normalizeDigitsForPreview(input: string): string {
  let out = "";
  for (const ch of input) {
    out += ARABIC_INDIC_MAP[ch] ?? ch;
  }
  return out;
}

/** Tests whether a cell sample string represents a valid numeric value without ASCII coercion. */
export function isNumericSample(raw: string, allowDecimal: boolean): boolean {
  if (isMaskedSentinelSample(raw)) return true;
  const normalized = normalizeDigitsForPreview(raw).trim();
  if (!normalized) return true;

  // Strip common thousands separators & currency codes/symbols surrounding numbers
  const cleaned = normalized
    .replace(/[\s,_]/g, "")
    .replace(/^(USD|EUR|GBP|EGP|SAR|AED|\$|€|£|ج\.م|ر\.س)/i, "")
    .replace(/(USD|EUR|GBP|EGP|SAR|AED|\$|€|£|ج\.م|ر\.س)$/i, "");

  if (!cleaned) return false;
  if (allowDecimal) {
    return /^[+-]?(\d+(\.\d+)?|\.\d+)$/.test(cleaned);
  }
  return /^[+-]?\d+$/.test(cleaned);
}

const VALID_BOOL_TOKENS = new Set([
  "true",
  "false",
  "1",
  "0",
  "yes",
  "no",
  "y",
  "n",
  "نعم",
  "لا",
  "صح",
  "خطأ",
]);

/** Tests whether a cell sample string represents a recognized boolean token. */
export function isBoolSample(raw: string): boolean {
  if (isMaskedSentinelSample(raw)) return true;
  const token = raw.trim().toLowerCase();
  return !token || VALID_BOOL_TOKENS.has(token);
}

/** Tests whether a cell sample string looks like an ISO/common date or Excel serial number. */
export function isDateSample(raw: string): boolean {
  if (isMaskedSentinelSample(raw)) return true;
  const trimmed = normalizeDigitsForPreview(raw).trim();
  if (!trimmed) return true;
  if (/^\d{4,5}(\.\d+)?$/.test(trimmed)) {
    const serial = Number(trimmed);
    return serial > 1 && serial < 95000;
  }
  return !Number.isNaN(Date.parse(trimmed));
}

/**
 * Validates all mapped columns on a sheet against target column types, mutability, FLS restrictions,
 * and live sample cell values.
 */
export function validateSheetMappings(
  sheet: DataExchangeInspectedSheetDto,
  mappings: DataExchangeColumnMapping[],
  descriptor: DataExchangeEntityDescriptor | null,
  restrictedFieldKeys: ReadonlySet<string>
): MappingCompatibilityIssue[] {
  if (!descriptor) return [];

  const columnMap = new Map<string, DataExchangeColumnDescriptor>();
  for (const col of descriptor.columns) {
    columnMap.set(col.key.toLowerCase(), col);
  }

  const issues: MappingCompatibilityIssue[] = [];

  for (const mapping of mappings) {
    if (!mapping.targetFieldKey) continue;
    const target = columnMap.get(mapping.targetFieldKey.toLowerCase());
    if (!target) continue;

    if (
      !target.isMappable ||
      target.isAutoGenerated ||
      target.direction === "SystemGenerated" ||
      target.direction === "ExportOnly"
    ) {
      issues.push({
        sourceColumnHeader: mapping.sourceColumnHeader,
        targetFieldKey: mapping.targetFieldKey,
        reasonCode: "READ_ONLY",
      });
      continue;
    }

    if (restrictedFieldKeys.has(target.key)) {
      issues.push({
        sourceColumnHeader: mapping.sourceColumnHeader,
        targetFieldKey: mapping.targetFieldKey,
        reasonCode: "RESTRICTED",
      });
      continue;
    }

    const samples = sheet.sampleRows
      .map((row) => row[mapping.sourceColumnHeader] ?? "")
      .map((v) => v.trim())
      .filter((v) => v.length > 0);

    if (samples.length === 0) continue;

    if (target.dataType === "Int" || target.dataType === "Decimal") {
      const bad = samples.find((s) => !isNumericSample(s, target.dataType === "Decimal"));
      if (bad) {
        issues.push({
          sourceColumnHeader: mapping.sourceColumnHeader,
          targetFieldKey: target.key,
          reasonCode: "NON_NUMERIC_VALUES",
          sampleValue: bad,
        });
      }
    } else if (target.dataType === "Bool") {
      const bad = samples.find((s) => !isBoolSample(s));
      if (bad) {
        issues.push({
          sourceColumnHeader: mapping.sourceColumnHeader,
          targetFieldKey: target.key,
          reasonCode: "INVALID_BOOL",
          sampleValue: bad,
        });
      }
    } else if (target.dataType === "Date" || target.dataType === "DateTime") {
      const bad = samples.find((s) => !isDateSample(s));
      if (bad) {
        issues.push({
          sourceColumnHeader: mapping.sourceColumnHeader,
          targetFieldKey: target.key,
          reasonCode: "INVALID_DATE",
          sampleValue: bad,
        });
      }
    }
  }

  return issues;
}

/**
 * Computes required mappable fields that are not yet assigned on a given sheet mapping.
 */
export function findMissingRequiredFields(
  mappings: DataExchangeColumnMapping[],
  descriptor: DataExchangeEntityDescriptor | null
): DataExchangeColumnDescriptor[] {
  if (!descriptor) return [];
  const mappedTargets = new Set(
    mappings.map((m) => m.targetFieldKey.toLowerCase()).filter(Boolean)
  );
  return descriptor.columns.filter(
    (col) =>
      col.isRequired &&
      col.isMappable &&
      !col.isAutoGenerated &&
      col.direction !== "SystemGenerated" &&
      col.direction !== "ExportOnly" &&
      !mappedTargets.has(col.key.toLowerCase())
  );
}

/**
 * Determines whether an inspected single-sheet upload qualifies for Express Smart-Template Dry-Run skip.
 */
export function isExpressTemplateMatch(
  sheet: DataExchangeInspectedSheetDto,
  mappings: DataExchangeColumnMapping[],
  descriptor: DataExchangeEntityDescriptor | null,
  restrictedFieldKeys: ReadonlySet<string>
): boolean {
  if (!descriptor || sheet.isEmpty) return false;
  if (validateSheetMappings(sheet, mappings, descriptor, restrictedFieldKeys).length > 0) {
    return false;
  }
  if (findMissingRequiredFields(mappings, descriptor).length > 0) {
    return false;
  }
  const highConfidenceTargets = new Set(
    sheet.suggestedMappings
      .filter(
        (s) =>
          s.targetFieldKey &&
          !s.isDiagnosticColumn &&
          (s.confidence === "Exact" || s.confidence === "High")
      )
      .map((s) => s.targetFieldKey!.toLowerCase())
  );

  const requiredCols = descriptor.columns.filter(
    (c) => c.isRequired && c.isMappable && !c.isAutoGenerated
  );
  return requiredCols.every((c) => highConfidenceTargets.has(c.key.toLowerCase()));
}

/** Formats raw file size in bytes into human-readable units. */
export function formatByteSize(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(2)} MB`;
}

const NULL_PLACEHOLDER_SET = new Set([
  "n/a",
  "#n/a",
  "na",
  "null",
  "nil",
  "none",
  "-",
  "—",
  "–",
  "--",
  "غير متاح",
  "لا يوجد",
]);

const PREFIX_SUFFIX_CURRENCY_PATTERNS = [
  /^(SAR|EGP|AED|USD|EUR|GBP|ر\.س\.|ر\.س|ج\.م\.|ج\.م|د\.إ\.|د\.إ|\$|€|£|﷼)\s*/i,
  /\s*(SAR|EGP|AED|USD|EUR|GBP|ر\.س\.|ر\.س|ج\.م\.|ج\.م|د\.إ\.|د\.إ|\$|€|£|﷼)$/i,
];

/**
 * Normalizes a raw cell sample string using the given transform rule and target data type,
 * producing a deterministic preview matching backend SpreadsheetValueNormalizer in linear time O(n).
 */
export function previewNormalizedSample(
  rawSample: string,
  rule?: DataExchangeTransformRule | null,
  dataType?: string
): string {
  if (rawSample == null || rawSample === "") {
    return rule?.defaultValue ?? "";
  }

  let val = String(rawSample);

  // 1. Unicode Compatibility (ZWNJ, ZWJ, BOM, LTR/RTL marks, NBSP)
  if (rule?.normalizeUnicodeCompatibility !== false) {
    val = val
      .replace(/\u00A0/g, " ")
      .replace(/[\u200B-\u200D\uFEFF\u200E\u200F\u202A-\u202E\u2066-\u2069]/g, "");
  }

  // 2. Trim
  if (rule?.trim !== false) {
    val = val.trim();
  }

  // 3. Signed numeric apostrophe unescape (e.g. '+123, preserve genuine formula '=1+1)
  if (val.startsWith("'") && /^'[+-]?\d/.test(val)) {
    val = val.slice(1);
  }

  // 4. Arabic Diacritics and Letters
  if (rule?.stripArabicDiacritics !== false) {
    val = val.replace(/[\u064B-\u065F\u0670\u0640]/g, "");
  }
  if (rule?.normalizeArabicLetters) {
    val = val
      .replace(/[\u0622\u0623\u0625\u0671]/g, "\u0627")
      .replace(/[\u0649\u06CC]/g, "\u064A")
      .replace(/\u06A9/g, "\u0643");
  }

  // 5. Canonicalize Null Tokens
  if (rule?.canonicalizeNullTokens !== false) {
    const candidate = val.trim().toLowerCase();
    if (NULL_PLACEHOLDER_SET.has(candidate)) {
      return rule?.defaultValue ?? "";
    }
  }

  // 6. Whitespace collapse
  if (rule?.collapseWhitespace !== false) {
    val = val.replace(/\s+/g, " ");
    if (rule?.trim !== false) {
      val = val.trim();
    }
  }

  // 7. Multi-Value Delimiter splitting & deduplication
  if (rule?.multiValueDelimiter && val.includes(rule.multiValueDelimiter)) {
    const parts = val.split(rule.multiValueDelimiter);
    const seen = new Set<string>();
    const deduped: string[] = [];
    for (const p of parts) {
      const cleanPart = p.trim();
      if (!cleanPart) continue;
      const lower = cleanPart.toLowerCase();
      if (!seen.has(lower)) {
        seen.add(lower);
        deduped.push(cleanPart);
      }
    }
    val = deduped.join(rule.multiValueDelimiter + " ");
  }

  // 8. Numeric normalization (Digits, Accounting Negatives, Currency, Grouping)
  const isNumericType = dataType === "Int" || dataType === "Decimal" || dataType === "Currency";
  if (isNumericType || rule?.stripCurrencyAndGrouping || rule?.convertAccountingNegatives) {
    // Digits
    val = normalizeDigitsForPreview(val);

    let isNegative = false;
    let numSpan = val.trim();

    // Strip trailing percent if present
    if (numSpan.endsWith("%") || numSpan.endsWith("٪")) {
      numSpan = numSpan.slice(0, -1).trim();
    }

    // Accounting negatives e.g. (1,250.50)
    if (
      rule?.convertAccountingNegatives !== false &&
      numSpan.startsWith("(") &&
      numSpan.endsWith(")")
    ) {
      isNegative = true;
      numSpan = numSpan.slice(1, -1).trim();
    } else if (numSpan.startsWith("-")) {
      isNegative = true;
      numSpan = numSpan.slice(1).trim();
    } else if (numSpan.startsWith("+")) {
      numSpan = numSpan.slice(1).trim();
    }

    // Strip Currency prefix/suffix
    if (rule?.stripCurrencyAndGrouping !== false || isNumericType) {
      for (const pat of PREFIX_SUFFIX_CURRENCY_PATTERNS) {
        numSpan = numSpan.replace(pat, "").trim();
      }

      // Grouping separator handling (e.g. 1,250.50 or 1.250,50)
      const dotIdx = numSpan.lastIndexOf(".");
      const commaIdx = numSpan.lastIndexOf(",");
      if (dotIdx > -1 && commaIdx > -1) {
        if (dotIdx > commaIdx) {
          // US format: 1,250.50 -> 1250.50
          numSpan = numSpan.replace(/,/g, "");
        } else {
          // European format: 1.250,50 -> 1250.50
          numSpan = numSpan.replace(/\./g, "").replace(",", ".");
        }
      } else if (commaIdx > -1 && dotIdx === -1) {
        // e.g. 1,250 vs 12,5
        const afterComma = numSpan.slice(commaIdx + 1);
        if (afterComma.length === 3 && /^\d{1,3},\d{3}$/.test(numSpan)) {
          numSpan = numSpan.replace(",", "");
        } else {
          numSpan = numSpan.replace(",", ".");
        }
      }
    }

    // If valid number resulted, apply negative sign
    if (numSpan && !Number.isNaN(Number(numSpan))) {
      val = isNegative ? `-${numSpan}` : numSpan;
    }
  }

  // 9. Phone normalization (E.164 with defaultCountryDialCode)
  if (rule?.defaultCountryDialCode || dataType === "Phone") {
    const rawDigits = normalizeDigitsForPreview(val).replace(/[^\d+]/g, "");
    if (rawDigits) {
      const defaultDial = rule?.defaultCountryDialCode || "";
      const dialCode = defaultDial.startsWith("+")
        ? defaultDial
        : defaultDial
          ? `+${defaultDial}`
          : "";

      if (rawDigits.startsWith("00")) {
        val = `+${rawDigits.slice(2)}`;
      } else if (rawDigits.startsWith("+")) {
        val = rawDigits;
      } else if (dialCode) {
        if (rawDigits.startsWith("0")) {
          val = `${dialCode}${rawDigits.slice(1)}`;
        } else {
          val = `${dialCode}${rawDigits}`;
        }
      }
    }
  }

  // 10. Email normalization
  if (rule?.normalizeEmailAddress || dataType === "Email") {
    let email = val.trim();
    if (email.toLowerCase().startsWith("mailto:")) {
      email = email.slice(7).split("?")[0].trim();
    }
    const match = /<([^>]+)>/.exec(email);
    if (match) {
      email = match[1].trim();
    }
    const atIdx = email.lastIndexOf("@");
    if (atIdx > 0 && atIdx < email.length - 1) {
      val = `${email.slice(0, atIdx)}@${email.slice(atIdx + 1).toLowerCase()}`;
    }
  }

  // 11. Default value fallback
  if (!val && rule?.defaultValue) {
    val = rule.defaultValue;
  }

  // 12. Casing
  if (rule?.caseMode === "Upper" || rule?.uppercase) {
    val = val.toUpperCase();
  } else if (rule?.caseMode === "Lower" || rule?.lowercase) {
    val = val.toLowerCase();
  } else if (rule?.caseMode === "Title") {
    val = val.replace(/\b\w/g, (c) => c.toUpperCase());
  }

  return val;
}
