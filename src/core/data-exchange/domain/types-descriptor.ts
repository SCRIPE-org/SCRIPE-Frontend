/**
 * Entity catalog, column metadata, and spreadsheet upload inspection contracts
 * for SCRIPE Data Exchange Studio.
 */
import type {
  DataExchangeColumnType,
  DataExchangeFieldDirection,
  DataExchangeImportMode,
} from "./types-common";

/** Dynamic metadata descriptor for a single target column on an entity. */
export interface DataExchangeColumnDescriptor {
  key: string;
  displayNameEn: string;
  displayNameAr: string;
  dataType: DataExchangeColumnType;
  isRequired: boolean;
  isNullable: boolean;
  isAutoGenerated: boolean;
  isMappable: boolean;
  isNaturalKey: boolean;
  direction: DataExchangeFieldDirection;
  maxLength?: number | null;
  minValue?: number | null;
  maxValue?: number | null;
  allowedValues?: string[] | null;
  lookupEntityKey?: string | null;
  supportsAutoCreateLookup: boolean;
  sampleValueEn?: string | null;
  sampleValueAr?: string | null;
  descriptionEn?: string | null;
  descriptionAr?: string | null;
  aliases?: string[] | null;
}

/** Full entity capability and column catalog returned for an entity. */
export interface DataExchangeEntityDescriptor {
  entityKey: string;
  owningModule: string;
  displayNameEn: string;
  displayNameAr: string;
  descriptionEn: string;
  descriptionAr: string;
  requiredFeatureKey: string;
  moduleImportFeatureKey: string;
  requiredImportPermission: string;
  requiredExportPermission: string;
  requiredCreatePermission: string;
  requiredUpdatePermission: string;
  requiredViewPermission: string;
  quotaResourceType?: string | null;
  supportsBulkAutoCreateLookup: boolean;
  supportsIdentityOnboardingModes: boolean;
  supportedModes: DataExchangeImportMode[];
  parentEntityKeys: string[];
  columns: DataExchangeColumnDescriptor[];
  quotaFeatureKey?: string | null;
  relatedMultiSheetEntityKeys?: string[];
}

/** Summary entry returned by GET /api/v1/data-transfer/entities. */
export interface DataExchangeEntitySummaryDto {
  entityKey: string;
  owningModule: string;
  displayNameEn: string;
  displayNameAr: string;
  descriptionEn: string;
  descriptionAr: string;
  supportsBulkAutoCreateLookup: boolean;
  supportsIdentityOnboardingModes: boolean;
  supportedModes: DataExchangeImportMode[];
  parentEntityKeys: string[];
  remainingQuotaSlots?: number | null;
  quotaMaxLimit?: number | null;
  isImportFeatureEnabled: boolean;
  isExportFeatureEnabled: boolean;
  canImport: boolean;
  canExport: boolean;
  relatedMultiSheetEntityKeys?: string[];
}

export type DataExchangeEntitySummary = DataExchangeEntitySummaryDto;

/** Detailed entity descriptor combined with live tenant quota, features, permissions, and FLS. */
export interface DataExchangeDescriptorResponseDto {
  descriptor: DataExchangeEntityDescriptor;
  quotaUsed?: number | null;
  quotaReserved?: number | null;
  quotaMaxLimit?: number | null;
  quotaRemainingSlots?: number | null;
  isQuotaEnforced: boolean;
  isImportFeatureEnabled: boolean;
  isExportFeatureEnabled: boolean;
  canImport: boolean;
  canExport: boolean;
  restrictedFieldKeys: string[];
  relatedMultiSheetEntityKeys?: string[];
}

/** Auto-suggested column mapping discovered during workbook inspection. */
export interface DataExchangeSuggestedMappingDto {
  sourceColumnHeader: string;
  targetFieldKey?: string | null;
  confidence: string;
  isDiagnosticColumn: boolean;
  targetDataType?: DataExchangeColumnType | null;
}

/** Inspected worksheet metadata, sample rows, and suggested mappings. */
export interface DataExchangeInspectedSheetDto {
  sheetName: string;
  suggestedEntityKey?: string | null;
  headers: string[];
  sampleRows: Record<string, string | null>[];
  estimatedRowCount: number;
  isEmpty: boolean;
  suggestedMappings: DataExchangeSuggestedMappingDto[];
}

/** Server response after uploading a workbook for OWASP validation and inspection. */
export interface DataExchangeInspectResponseDto {
  uploadId: string;
  fileName: string;
  format: string;
  byteSize: number;
  entityKey: string;
  isMultiSheet: boolean;
  sheets: DataExchangeInspectedSheetDto[];
}
