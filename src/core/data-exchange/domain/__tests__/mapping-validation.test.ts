import { describe, expect, it } from "vitest";
import {
  findMissingRequiredFields,
  formatByteSize,
  isBoolSample,
  isDateSample,
  isExpressTemplateMatch,
  isMaskedSentinelSample,
  isNumericSample,
  normalizeDigitsForPreview,
  previewNormalizedSample,
  validateSheetMappings,
} from "../mapping-validation";
import type {
  DataExchangeColumnDescriptor,
  DataExchangeColumnMapping,
  DataExchangeEntityDescriptor,
  DataExchangeInspectedSheetDto,
} from "../types";

function makeColumn(
  overrides: Partial<DataExchangeColumnDescriptor> & { key: string }
): DataExchangeColumnDescriptor {
  return {
    displayNameEn: overrides.key,
    displayNameAr: overrides.key,
    dataType: "String",
    isRequired: false,
    isNullable: true,
    isAutoGenerated: false,
    isMappable: true,
    isNaturalKey: false,
    direction: "Both",
    supportsAutoCreateLookup: false,
    ...overrides,
  };
}

const sampleDescriptor: DataExchangeEntityDescriptor = {
  entityKey: "crm.lead",
  owningModule: "CRM",
  displayNameEn: "Leads",
  displayNameAr: "العملاء المحتملون",
  descriptionEn: "Lead import/export",
  descriptionAr: "استيراد وتصدير العملاء المحتملين",
  requiredFeatureKey: "CRM.Enabled",
  moduleImportFeatureKey: "CRM.DataImport",
  requiredImportPermission: "crm.leads.import",
  requiredExportPermission: "crm.leads.export",
  requiredCreatePermission: "crm.leads.create",
  requiredUpdatePermission: "crm.leads.update",
  requiredViewPermission: "crm.leads.read",
  supportsBulkAutoCreateLookup: true,
  supportsIdentityOnboardingModes: false,
  supportedModes: ["Insert", "Update", "Upsert"],
  parentEntityKeys: [],
  columns: [
    makeColumn({
      key: "Id",
      dataType: "String",
      isAutoGenerated: true,
      isMappable: false,
      direction: "ExportOnly",
    }),
    makeColumn({
      key: "Title",
      dataType: "String",
      isRequired: true,
      isNullable: false,
    }),
    makeColumn({
      key: "SeatsCount",
      dataType: "Int",
      isRequired: false,
    }),
    makeColumn({
      key: "EstimatedValue",
      dataType: "Decimal",
      isRequired: false,
    }),
    makeColumn({
      key: "IsQualified",
      dataType: "Bool",
    }),
    makeColumn({
      key: "FollowUpDate",
      dataType: "Date",
    }),
    makeColumn({
      key: "InternalMargin",
      dataType: "Decimal",
    }),
  ],
};

describe("mapping-validation domain rules", () => {
  it("normalizes Eastern Arabic-Indic numerals and decimal separator", () => {
    expect(normalizeDigitsForPreview("١٢٣٤٫٥٦")).toBe("1234.56");
    expect(normalizeDigitsForPreview("٥٠٠")).toBe("500");
  });

  it("validates numeric samples strictly without ASCII character coercion", () => {
    expect(isNumericSample("1250", false)).toBe(true);
    expect(isNumericSample("SAR 1,250", false)).toBe(true);
    expect(isNumericSample("١٢٥٠", false)).toBe(true);
    expect(isNumericSample("SAR 1,250.75", true)).toBe(true);

    expect(isNumericSample("12.5", false)).toBe(false);
    expect(isNumericSample("ABC", false)).toBe(false);
    expect(isNumericSample("ABC", true)).toBe(false);
    expect(isNumericSample("12abc", true)).toBe(false);
  });

  it("validates bilingual boolean and ISO/Excel serial date samples", () => {
    expect(isBoolSample("true")).toBe(true);
    expect(isBoolSample("0")).toBe(true);
    expect(isBoolSample("نعم")).toBe(true);
    expect(isBoolSample("لا")).toBe(true);
    expect(isBoolSample("invalid")).toBe(false);

    expect(isDateSample("2026-11-13")).toBe(true);
    expect(isDateSample("45609")).toBe(true);
    expect(isDateSample("not-a-date")).toBe(false);
  });

  it("flags read-only/auto-generated, FLS-restricted, and incompatible sample types", () => {
    const sheet: DataExchangeInspectedSheetDto = {
      sheetName: "Leads",
      headers: ["ColId", "ColTitle", "ColSeats", "ColBool", "ColDate", "ColMargin"],
      sampleRows: [
        {
          ColId: "guid-1",
          ColTitle: "Stadium Sponsorship",
          ColSeats: "ABC",
          ColBool: "invalid-bool",
          ColDate: "not-a-date",
          ColMargin: "15.5",
        },
      ],
      estimatedRowCount: 1,
      isEmpty: false,
      suggestedMappings: [],
    };

    const mappings: DataExchangeColumnMapping[] = [
      { sourceColumnHeader: "ColId", targetFieldKey: "Id" },
      { sourceColumnHeader: "ColTitle", targetFieldKey: "Title" },
      { sourceColumnHeader: "ColSeats", targetFieldKey: "SeatsCount" },
      { sourceColumnHeader: "ColBool", targetFieldKey: "IsQualified" },
      { sourceColumnHeader: "ColDate", targetFieldKey: "FollowUpDate" },
      { sourceColumnHeader: "ColMargin", targetFieldKey: "InternalMargin" },
    ];

    const issues = validateSheetMappings(
      sheet,
      mappings,
      sampleDescriptor,
      new Set(["InternalMargin"])
    );

    expect(issues).toEqual([
      {
        sourceColumnHeader: "ColId",
        targetFieldKey: "Id",
        reasonCode: "READ_ONLY",
      },
      {
        sourceColumnHeader: "ColSeats",
        targetFieldKey: "SeatsCount",
        reasonCode: "NON_NUMERIC_VALUES",
        sampleValue: "ABC",
      },
      {
        sourceColumnHeader: "ColBool",
        targetFieldKey: "IsQualified",
        reasonCode: "INVALID_BOOL",
        sampleValue: "invalid-bool",
      },
      {
        sourceColumnHeader: "ColDate",
        targetFieldKey: "FollowUpDate",
        reasonCode: "INVALID_DATE",
        sampleValue: "not-a-date",
      },
      {
        sourceColumnHeader: "ColMargin",
        targetFieldKey: "InternalMargin",
        reasonCode: "RESTRICTED",
      },
    ]);
  });

  it("detects missing required fields and Express Smart-Template match eligibility", () => {
    const sheet: DataExchangeInspectedSheetDto = {
      sheetName: "Leads",
      headers: ["Title", "EstimatedValue"],
      sampleRows: [{ Title: "Academy Expansion", EstimatedValue: "25000" }],
      estimatedRowCount: 1,
      isEmpty: false,
      suggestedMappings: [
        {
          sourceColumnHeader: "Title",
          targetFieldKey: "Title",
          confidence: "Exact",
          isDiagnosticColumn: false,
          targetDataType: "String",
        },
        {
          sourceColumnHeader: "EstimatedValue",
          targetFieldKey: "EstimatedValue",
          confidence: "High",
          isDiagnosticColumn: false,
          targetDataType: "Decimal",
        },
      ],
    };

    const incomplete: DataExchangeColumnMapping[] = [
      { sourceColumnHeader: "EstimatedValue", targetFieldKey: "EstimatedValue" },
    ];
    expect(findMissingRequiredFields(incomplete, sampleDescriptor).map((c) => c.key)).toEqual([
      "Title",
    ]);
    expect(isExpressTemplateMatch(sheet, incomplete, sampleDescriptor, new Set())).toBe(false);

    const complete: DataExchangeColumnMapping[] = [
      { sourceColumnHeader: "Title", targetFieldKey: "Title" },
      { sourceColumnHeader: "EstimatedValue", targetFieldKey: "EstimatedValue" },
    ];
    expect(findMissingRequiredFields(complete, sampleDescriptor)).toEqual([]);
    expect(isExpressTemplateMatch(sheet, complete, sampleDescriptor, new Set())).toBe(true);
  });

  it("formats byte sizes consistently", () => {
    expect(formatByteSize(512)).toBe("512 B");
    expect(formatByteSize(2048)).toBe("2.0 KB");
    expect(formatByteSize(5 * 1024 * 1024)).toBe("5.00 MB");
  });

  it("recognizes masked sentinels (••••••, ***, [REDACTED]) during roundtrip preview", () => {
    expect(isMaskedSentinelSample("••••••")).toBe(true);
    expect(isMaskedSentinelSample("***")).toBe(true);
    expect(isMaskedSentinelSample("[REDACTED]")).toBe(true);
    expect(isMaskedSentinelSample("[MASKED]")).toBe(true);
    expect(isMaskedSentinelSample("normal-value")).toBe(false);

    expect(isNumericSample("••••••", true)).toBe(true);
    expect(isNumericSample("***", false)).toBe(true);
    expect(isBoolSample("••••••")).toBe(true);
    expect(isDateSample("[REDACTED]")).toBe(true);
  });

  describe("previewNormalizedSample", () => {
    it("canonicalizes null placeholders (N/A, —, غير متاح) to empty string or default value", () => {
      expect(previewNormalizedSample("N/A")).toBe("");
      expect(previewNormalizedSample("—")).toBe("");
      expect(previewNormalizedSample("غير متاح")).toBe("");
      expect(previewNormalizedSample("None", { defaultValue: "N/A_DEFAULT" })).toBe("N/A_DEFAULT");
      expect(previewNormalizedSample(null as any, { defaultValue: "FALLBACK" })).toBe("FALLBACK");
    });

    it("sanitizes zero-width invisible marks and non-breaking spaces", () => {
      const input = "Hello\u200B\u00A0World\uFEFF";
      expect(previewNormalizedSample(input)).toBe("Hello World");
    });

    it("strips Arabic diacritics and optionally folds Arabic letter variants", () => {
      expect(previewNormalizedSample("مُحَمَّد")).toBe("محمد");
      expect(previewNormalizedSample("إِبْرَاهِيم", { stripArabicDiacritics: true, normalizeArabicLetters: true })).toBe("ابراهيم");
    });

    it("strips currency symbols and thousands grouping in US and European formats", () => {
      expect(previewNormalizedSample("SAR 1,250.50", { stripCurrencyAndGrouping: true }, "Decimal")).toBe("1250.50");
      expect(previewNormalizedSample("1.250,50 €", { stripCurrencyAndGrouping: true }, "Decimal")).toBe("1250.50");
      expect(previewNormalizedSample("$ 5,000", { stripCurrencyAndGrouping: true }, "Int")).toBe("5000");
    });

    it("converts accounting negative parentheses to standard negative sign", () => {
      expect(previewNormalizedSample("(1,250.50)", { convertAccountingNegatives: true, stripCurrencyAndGrouping: true }, "Decimal")).toBe("-1250.50");
      expect(previewNormalizedSample("(500)", { convertAccountingNegatives: true }, "Int")).toBe("-500");
    });

    it("normalizes phone numbers to E.164 with defaultCountryDialCode", () => {
      expect(previewNormalizedSample("0501234567", { defaultCountryDialCode: "+966" }, "Phone")).toBe("+966501234567");
      expect(previewNormalizedSample("00966501234567", { defaultCountryDialCode: "+966" }, "Phone")).toBe("+966501234567");
      expect(previewNormalizedSample("+966 50 123 4567", {}, "Phone")).toBe("+966501234567");
    });

    it("normalizes email addresses by stripping mailto and lowercasing domain part", () => {
      expect(previewNormalizedSample("mailto:Sales <INFO@Domain.COM>?subject=hi", { normalizeEmailAddress: true }, "Email")).toBe("INFO@domain.com");
      expect(previewNormalizedSample("Support <support@scripe.org>", { normalizeEmailAddress: true }, "Email")).toBe("support@scripe.org");
    });

    it("splits, trims, and deduplicates multi-value delimited cells", () => {
      expect(previewNormalizedSample("Alpha; Beta; alpha; Gamma", { multiValueDelimiter: ";" })).toBe("Alpha; Beta; Gamma");
    });

    it("applies casing transformations cleanly", () => {
      expect(previewNormalizedSample("riyadh central", { caseMode: "Upper" })).toBe("RIYADH CENTRAL");
      expect(previewNormalizedSample("RIYADH CENTRAL", { caseMode: "Lower" })).toBe("riyadh central");
      expect(previewNormalizedSample("riyadh central facility", { caseMode: "Title" })).toBe("Riyadh Central Facility");
    });
  });
});
