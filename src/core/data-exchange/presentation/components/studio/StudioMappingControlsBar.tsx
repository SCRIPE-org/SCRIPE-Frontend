"use client";

import React from "react";
import { CheckCircle2, Lock, Sparkles } from "lucide-react";
import { Alert, AlertDescription, AlertTitle } from "@core/ui/alert";
import { Badge } from "@core/ui/badge";
import { Button } from "@core/ui/button";
import { Card } from "@core/ui/card";
import { Checkbox } from "@core/ui/checkbox";
import { Label } from "@core/ui/label";
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@core/ui/select";
import { Tabs, TabsList, TabsTrigger } from "@core/ui/tabs";
import { useI18n } from "@core/providers/i18n-provider";
import { getEntityDisplayName } from "../../utils/entity-display-names";
import { StudioMappingPresetBar } from "./StudioMappingPresetBar";
import type {
  DataExchangeImportMode,
  DataExchangeIdentityOnboardingMode,
} from "../../../domain/types";
import type { useDataExchangeStudioViewModel } from "../../viewmodels/useDataExchangeStudioViewModel";

export interface StudioMappingControlsBarProps {
  vm: ReturnType<typeof useDataExchangeStudioViewModel>;
  onPromptReplaceFile: () => void;
}

/**
 * Top controls ribbon, express auto-skip banner, multi-sheet DAG tabs,
 * batch execution settings (including Identity Onboarding mode), and system-generated fields lock banner.
 */
export function StudioMappingControlsBar({
  vm,
  onPromptReplaceFile,
}: StudioMappingControlsBarProps) {
  const { language, t } = useI18n();
  const isAr = language === "ar";

  const {
    inspectResult,
    activeSheet,
    activeSheetState,
    sheetStates,
    expressReady,
    presets,
    presetNameInput,
    isSavingPreset,
    isDryRunning,
    isMultiSheet,
    importMode,
    onboardingMode,
    allowCreateMissingLookups,
    compatibilityIssuesBySheet,
    missingRequiredBySheet,
    activeDescriptorResponse,
    reAutoMapActiveSheet,
    applyPreset,
    setPresetNameInput,
    saveCurrentPreset,
    runDryRun,
    setActiveSheetName,
    setImportMode,
    setOnboardingMode,
    updateSheetMeta,
    setAllowCreateMissingLookups,
  } = vm;

  if (!inspectResult || !activeSheet || !activeSheetState) return null;

  const activeDesc = activeDescriptorResponse?.descriptor;
  const supportedModes = (activeDesc?.supportedModes ?? [
    "Insert",
    "Update",
    "Upsert",
  ]) as DataExchangeImportMode[];

  const readOnlyColumns = (activeDesc?.columns ?? []).filter(
    (c) =>
      c.isAutoGenerated ||
      c.direction === "SystemGenerated" ||
      c.direction === "ExportOnly" ||
      !c.isMappable
  );

  return (
    <div className="space-y-4">
      {/* Top File + Presets Ribbon */}
      <StudioMappingPresetBar
        fileName={inspectResult.fileName}
        byteSize={inspectResult.byteSize}
        sheetCount={inspectResult.sheets.length}
        onPromptReplaceFile={onPromptReplaceFile}
        onAutoMap={reAutoMapActiveSheet}
        presets={presets}
        presetNameInput={presetNameInput}
        isSavingPreset={isSavingPreset}
        onSelectPreset={applyPreset}
        onPresetNameChange={setPresetNameInput}
        onSavePreset={saveCurrentPreset}
      />

      {/* Express Auto-Skip Banner */}
      {expressReady && (
        <Alert
          variant="success"
          className="flex flex-wrap items-center justify-between gap-3 border-success/30 bg-success/10"
        >
          <div>
            <AlertTitle className="text-sm font-semibold">
              {t("dataExchange.mapping.expressReadyTitle")}
            </AlertTitle>
            <AlertDescription className="text-xs text-nx-ink-2">
              {t("dataExchange.mapping.expressReadyDesc")}
            </AlertDescription>
          </div>
          <Button
            type="button"
            variant="default"
            size="sm"
            loading={isDryRunning}
            onClick={runDryRun}
            className="bg-nx-accent-fill text-nx-on-fill font-medium"
          >
            <Sparkles className="me-1.5 h-4 w-4" />
            <span>{t("dataExchange.actions.expressDryRun")}</span>
          </Button>
        </Alert>
      )}

      {/* Multi-Sheet DAG Step Tabs */}
      {inspectResult.sheets.length > 1 && (
        <Tabs value={activeSheetState.sheetName} onValueChange={setActiveSheetName}>
          <TabsList variant="pill" className="flex-wrap gap-1 bg-nx-raised p-1">
            {inspectResult.sheets.map((s, idx) => {
              const sheetState = sheetStates.find((st) => st.sheetName === s.sheetName);
              const sheetEntityName = getEntityDisplayName(
                sheetState?.entityKey || s.sheetName,
                t,
                isAr
              );
              const sheetIssueCount =
                (compatibilityIssuesBySheet[s.sheetName]?.length ?? 0) +
                (missingRequiredBySheet[s.sheetName]?.length ?? 0);
              return (
                <TabsTrigger key={s.sheetName} value={s.sheetName} className="gap-1.5 text-xs py-1.5">
                  <Badge variant="outline" className="font-mono text-[10px] px-1 h-4">
                    {t("dataExchange.mapping.stepIndicator", {
                      step: idx + 1,
                      entity: sheetEntityName,
                    })}
                  </Badge>
                  <span className="font-medium">({s.sheetName})</span>
                  {sheetIssueCount > 0 ? (
                    <Badge variant="warning" className="px-1.5 py-0 text-[10px]">
                      {t("dataExchange.mapping.sheetIssuesCount", { count: sheetIssueCount })}
                    </Badge>
                  ) : (
                    <CheckCircle2 className="h-3.5 w-3.5 text-success" />
                  )}
                </TabsTrigger>
              );
            })}
          </TabsList>
        </Tabs>
      )}

      {/* Batch Execution Settings Bar */}
      <Card className="grid grid-cols-1 gap-4 border-nx-line bg-nx-surface p-4 md:grid-cols-2">
        <div className="space-y-1.5">
          <Label htmlFor="dx-import-mode" className="text-xs text-nx-ink-2">
            {t("dataExchange.mapping.importModeLabel")}
          </Label>
          <Select
            value={isMultiSheet ? activeSheetState.mode : importMode}
            onValueChange={(val) => {
              const nextMode = val as DataExchangeImportMode;
              if (isMultiSheet) updateSheetMeta(activeSheetState.sheetName, { mode: nextMode });
              else setImportMode(nextMode);
            }}
          >
            <SelectTrigger id="dx-import-mode" className="h-8 text-xs border-nx-line">
              <SelectValue />
            </SelectTrigger>
            <SelectContent>
              {supportedModes.map((mode) => (
                <SelectItem key={mode} value={mode}>
                  {mode === "Insert"
                    ? t("dataExchange.mapping.modeInsert")
                    : mode === "Update"
                      ? t("dataExchange.mapping.modeUpdate")
                      : t("dataExchange.mapping.modeUpsert")}
                </SelectItem>
              ))}
            </SelectContent>
          </Select>
        </div>

        <div className="flex flex-col justify-end gap-2">
          {activeDesc?.supportsIdentityOnboardingModes && (
            <div className="space-y-1.5">
              <Label htmlFor="dx-onboarding-mode" className="text-xs text-nx-ink-2">
                {t("dataExchange.mapping.onboardingModeLabel")}
              </Label>
              <Select
                value={onboardingMode}
                onValueChange={(val) =>
                  setOnboardingMode(val as DataExchangeIdentityOnboardingMode)
                }
              >
                <SelectTrigger id="dx-onboarding-mode" className="h-8 text-xs border-nx-line">
                  <SelectValue />
                </SelectTrigger>
                <SelectContent>
                  <SelectItem value="StagedPendingInvite">
                    {t("dataExchange.mapping.onboardingStaged")}
                  </SelectItem>
                  <SelectItem value="ThrottledActivationEmails">
                    {t("dataExchange.mapping.onboardingThrottled")}
                  </SelectItem>
                  <SelectItem value="OneTimeAutoPassword">
                    {t("dataExchange.mapping.onboardingOneTime")}
                  </SelectItem>
                </SelectContent>
              </Select>
            </div>
          )}

          {activeDesc?.supportsBulkAutoCreateLookup && (
            <div className="flex items-center gap-2 rounded-nx-control border border-nx-line bg-nx-ground px-3 py-1.5">
              <Checkbox
                id="dx-auto-create-lookups"
                checked={allowCreateMissingLookups}
                onCheckedChange={(c) => setAllowCreateMissingLookups(c === true)}
              />
              <Label
                htmlFor="dx-auto-create-lookups"
                className="cursor-pointer text-xs text-nx-ink font-medium"
              >
                {t("dataExchange.mapping.autoCreateLookups")}
              </Label>
            </div>
          )}
        </div>
      </Card>

      {/* System-generated read-only fields note */}
      {readOnlyColumns.length > 0 && (
        <div className="flex flex-wrap items-center gap-2 rounded-nx-control border border-nx-line bg-nx-raised/60 px-3.5 py-2 text-xs text-nx-ink-2">
          <Lock className="h-3.5 w-3.5 text-nx-ink-3 shrink-0" />
          <Badge variant="outline" className="text-[10px]">
            {t("dataExchange.mapping.autoGeneratedReadOnly")}
          </Badge>
          <span>{t("dataExchange.mapping.readOnlyTarget")}</span>
          <div className="flex flex-wrap items-center gap-1">
            {readOnlyColumns.slice(0, 6).map((rc) => (
              <Badge
                key={rc.key}
                variant="secondary"
                dir="ltr"
                className="font-mono text-[10px] text-nx-ink-3"
              >
                {rc.key}
              </Badge>
            ))}
          </div>
        </div>
      )}
    </div>
  );
}
