describe("DataExchangeExportDialog & DataExchangeFloatingDock MVVM views", () => {
  beforeEach(() => {
    vi.clearAllMocks();
    useDataExchangeJobsStore.setState({ jobs: [], isCollapsed: false });
  });

  it("hydrates exportable columns (excluding ImportOnly & FLS restricted) and exports via ViewModel", async () => {
    const onOpenChange = vi.fn();
    mockGetEntityDescriptor.mockResolvedValueOnce(buildDescriptor());
    mockExportToFile.mockResolvedValueOnce(undefined);

    render(
      <DataExchangeExportDialog
        open
        onOpenChange={onOpenChange}
        entityKey="crm.lead"
        activeSearch="ahly"
      />
    );

    await waitFor(() => {
      expect(screen.getByText("Full Name")).toBeTruthy();
    });
    expect(screen.queryByText("Import Only")).toBeNull();
    expect(screen.queryByText("Secret Notes")).toBeNull();

    fireEvent.click(screen.getByText("dataExchange.actions.downloadExport"));

    await waitFor(() => {
      expect(mockExportToFile).toHaveBeenCalledWith({
        entityKey: "crm.lead",
        format: "xlsx",
        locale: "en",
        search: "ahly",
        selectedColumns: ["fullName"],
        filters: null,
      });
      expect(onOpenChange).toHaveBeenCalledWith(false);
    });
  });

  it("queues background export through useDataExchangeExportViewModel and tracks the job", async () => {
    const onOpenChange = vi.fn();
    const queuedJob = buildJob({ id: "job-export-99", status: "Queued" });
    mockEnqueueExport.mockResolvedValueOnce(queuedJob);

    render(
      <DataExchangeExportDialog
        open
        onOpenChange={onOpenChange}
        entityKey="crm.lead"
        descriptor={buildDescriptor()}
      />
    );

    await waitFor(() => {
      expect(screen.getByText("Full Name")).toBeTruthy();
    });

    fireEvent.click(screen.getByText("dataExchange.exportDialog.exportInBackground"));

    await waitFor(() => {
      expect(mockEnqueueExport).toHaveBeenCalledTimes(1);
      expect(useDataExchangeJobsStore.getState().jobs[0]?.id).toBe("job-export-99");
      expect(mockToastInfo).toHaveBeenCalledTimes(1);
      expect(onOpenChange).toHaveBeenCalledWith(false);
    });
  });

  it("cancels active dock job through useDataExchangeFloatingDockViewModel", async () => {
    const runningJob = buildJob({ id: "job-active-1", status: "Running" });
    const cancelledJob = buildJob({ id: "job-active-1", status: "Cancelled" });
    useDataExchangeJobsStore.setState({ jobs: [runningJob], isCollapsed: false });
    mockCancelJob.mockResolvedValueOnce(cancelledJob);

    render(<DataExchangeFloatingDock />);

    const cancelBtn = await waitFor(() => screen.getByText("dataExchange.dock.cancel"));
    fireEvent.click(cancelBtn);

    await waitFor(() => {
      expect(mockCancelJob).toHaveBeenCalledWith("job-active-1");
      expect(useDataExchangeJobsStore.getState().jobs[0]?.status).toBe("Cancelled");
      expect(mockToastInfo).toHaveBeenCalledTimes(1);
    });
  });
});
