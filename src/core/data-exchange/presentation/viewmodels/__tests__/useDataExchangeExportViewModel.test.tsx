import { describe, it, expect, vi, beforeEach } from "vitest";
import { renderHook, act, waitFor } from "@testing-library/react";
import { useDataExchangeExportViewModel } from "../useDataExchangeExportViewModel";

let mockActiveTenantId: string | null = "tenant-a";

const getEntityDescriptorMock = vi.fn();
const exportToFileMock = vi.fn();
const enqueueExportMock = vi.fn();
const trackJobMock = vi.fn();

vi.mock("@core/hooks/useAdminContext", () => ({
  useAdminContext: () => ({ activeTenantId: mockActiveTenantId }),
}));

vi.mock("@core/providers/i18n-provider", () => ({
  useI18n: () => ({
    language: "en",
    direction: "ltr" as const,
    t: (k: string) => k,
  }),
}));

vi.mock("@core/di", () => ({
  getCoreContainer: () => ({
    dataExchangeRepository: {
      getEntityDescriptor: getEntityDescriptorMock,
      exportToFile: exportToFileMock,
      enqueueExport: enqueueExportMock,
    },
  }),
}));

vi.mock("../../store/useDataExchangeJobsStore", () => ({
  useDataExchangeJobsStore: {
    getState: () => ({ trackJob: trackJobMock }),
  },
}));

vi.mock("@core/ui/sileo-toast", () => ({
  toast: { info: vi.fn(), error: vi.fn(), success: vi.fn() },
}));

function makeDescriptor(cols: Array<{ key: string; direction?: string }>) {
  return {
    descriptor: {
      entityKey: "crm.lead",
      owningModule: "CRM",
      displayNameEn: "Leads",
      displayNameAr: "العملاء",
      supportedModes: ["Upsert"],
      columns: cols.map((c) => ({
        key: c.key,
        displayNameEn: c.key,
        displayNameAr: c.key,
        dataType: "String",
        isRequired: false,
        isMappable: true,
        isAutoGenerated: false,
        direction: (c.direction ?? "Both") as "Both" | "ImportOnly" | "ExportOnly" | "SystemGenerated",
      })),
    },
    quota: {
      allowed: true,
      planCode: "PRO",
      remainingRecords: 100,
      usedRecords: 0,
      maxRecords: 100,
    },
    canImport: true,
    canExport: true,
    isImportFeatureEnabled: true,
    isExportFeatureEnabled: true,
    restrictedFieldKeys: ["secret"],
  };
}

describe("useDataExchangeExportViewModel", () => {
  beforeEach(() => {
    vi.clearAllMocks();
    mockActiveTenantId = "tenant-a";
  });

  it("resets stale fetched descriptor on tenant switch and tracks loading state", async () => {
    getEntityDescriptorMock.mockResolvedValueOnce(
      makeDescriptor([{ key: "email" }, { key: "secret" }, { key: "importOnlyCol", direction: "ImportOnly" }])
    );

    const onOpenChange = vi.fn();
    const { result, rerender } = renderHook(
      ({ tenant }) => {
        mockActiveTenantId = tenant;
        return useDataExchangeExportViewModel({
          open: true,
          onOpenChange,
          entityKey: "crm.lead",
        });
      },
      { initialProps: { tenant: "tenant-a" } }
    );

    await waitFor(() => {
      expect(result.current.isLoadingDescriptor).toBe(false);
      expect(result.current.exportableColumns.map((c) => c.key)).toEqual(["email"]);
      expect(result.current.selectedColumns).toEqual(["email"]);
    });

    getEntityDescriptorMock.mockResolvedValueOnce(
      makeDescriptor([{ key: "fullName" }, { key: "email" }])
    );
    rerender({ tenant: "tenant-b" });

    await waitFor(() => {
      expect(result.current.exportableColumns.map((c) => c.key)).toEqual(["fullName", "email"]);
      expect(result.current.selectedColumns).toEqual(["fullName", "email"]);
    });
  });

  it("extracts ErrorResponse validation errors[] when export fails and allows selectAll/clear", async () => {
    const onOpenChange = vi.fn();
    const descriptor = makeDescriptor([{ key: "fullName" }, { key: "email" }]);

    const { result } = renderHook(() =>
      useDataExchangeExportViewModel({
        open: true,
        onOpenChange,
        entityKey: "crm.lead",
        descriptor: descriptor as never,
      })
    );

    expect(result.current.selectedColumns).toEqual(["fullName", "email"]);

    act(() => result.current.clearSelection());
    expect(result.current.selectedColumns).toEqual([]);

    act(() => result.current.selectAllColumns());
    expect(result.current.selectedColumns).toEqual(["fullName", "email"]);

    exportToFileMock.mockRejectedValueOnce({
      message: "HTTP 422",
      details: {
        message: "Export blocked",
        errors: ["Selected column email is masked."],
      },
    });

    await act(async () => {
      await result.current.handleExport();
    });

    expect(result.current.errorMessage).toBe("Export blocked: Selected column email is masked.");
    expect(onOpenChange).not.toHaveBeenCalled();
  });
});
